/** Every entry: { id, name, category, sources } with explicit sources first, then the name in each icon set. */
export const CATALOG = CATEGORIES.flatMap((cat) =>
  ROWS[cat.id].map(([name, ...explicit]) => {
    const s = slug(name);
    const auto = cat.order.map((k) => (k === 't' ? `t:${s}-filled` : `${k}:${s}`));
    // the game's originals keep their old ids (saves and tests refer to them)
    let id = s;
    if (cat.id === 'letters') id = `letter${name.slice(-1)}`;
    else if (cat.id === 'numbers') id = `number${name.slice(-1)}`;
    return { id, name, category: cat.id, sources: [...new Set([...explicit, ...auto])] };
  }),
);
