/** Bounding box of the '#' cells, so the drawing fills the board. */
function bbox(art) {
  let r0 = Infinity;
  let r1 = -1;
  let c0 = Infinity;
  let c1 = -1;
  art.forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      if (row[c] !== '#') continue;
      r0 = Math.min(r0, r);
      r1 = Math.max(r1, r);
      c0 = Math.min(c0, c);
      c1 = Math.max(c1, c);
    }
  });
  return { r0, c0, h: r1 - r0 + 1, w: c1 - c0 + 1 };
}
const BOXES = Object.fromEntries(Object.entries(SHAPE_ART).map(([k, art]) => [k, bbox(art)]));

/**
 * Is a normalized point inside a pixel-art shape? x and y are in [-1, 1], y points down.
 * The drawing keeps its proportions and is centred.
 * @param {string} name
 * @param {number} x
 * @param {number} y
 * @returns {boolean}
 */
export function insideArt(name, x, y) {
  const art = SHAPE_ART[name];
  const b = BOXES[name];
  const size = Math.max(b.w, b.h);
  const c = Math.floor(b.c0 - (size - b.w) / 2 + ((x + 1) / 2) * size);
  const r = Math.floor(b.r0 - (size - b.h) / 2 + ((y + 1) / 2) * size);
  return art[r]?.[c] === '#';
}
